/**
 * Calcula el valor de cuota mensual para la línea Haberes — AMAT únicamente.
 * Incorpora la lógica de sobreescritura para línea Ayuda y los adicionales
 * de membresía y seguro médico por repartición.
 *
 * Para CalculadorOferta (que maneja DOS DE AGOSTO, Ejército, BAPRO, Nación),
 * usar directamente TABLAS_CUOTA con la lógica de membresía del componente.
 *
 * @returns El valor de cuota calculado, o 0 si no hay datos en la grilla.
 */
export function calcularCuotaAMAT(
  entidad:     string,
  linea:       string,
  reparticion: string,
  monto:       number,
  cuotas:      number
): number {
  const vc = TABLAS_CUOTA[cuotas]?.[monto] ?? 0

  if (linea === 'Ayuda') {
    if (reparticion.includes('EDUCACION')) return 28996
    if (reparticion.includes('SALUD'))     return 15464
    return vc
  }

  const adicionalMembresia: Record<string, number> = {
    'MINISTERIO DE SEGURIDAD':           4300,
    'SERVICIO PENITENCIARIO BONAERENSE': 4300,
    'MINISTERIO DE EDUCACION':           9900,
    'MINISTERIO DE SALUD':               5172,
  }
  const cs = adicionalMembresia[reparticion] ?? 4300

  const med =
    monto <= 200000 ? 3850  :
    monto <= 300000 ? 6150  :
    monto <= 400000 ? 8150  :
    monto <= 600000 ? 11850 : 14850

  return vc + cs + med
}

/**
 * Devuelve los montos disponibles en la grilla para un plazo dado,
 * ordenados de menor a mayor.
 */
export function getMontosDisponibles(cuotas: number): number[] {
  const tabla = TABLAS_CUOTA[cuotas] ?? TABLAS_CUOTA[12]
  return Object.keys(tabla).map(Number).sort((a, b) => a - b)
}

